#!/usr/bin/env python3
"""
Patch the android/ and ios/ folders generated by `flutter create .` with what
DriverGuardian needs: location (incl. foreground service), notifications,
UPI app intents, camera (QR pass scanning), minSdk 23 and — when google-services.json is present —
the Google Services Gradle plugin for Firebase push, and — when android/app/upload-keystore.jks
is present — release signing with your own upload key (passwords read from environment variables
ANDROID_KEYSTORE_PASSWORD, ANDROID_KEY_ALIAS, ANDROID_KEY_PASSWORD).
Safe to run more than once.
Developed & Powered by Marian Anbu Juwan
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, 'android')


def read(p):
    with open(p, encoding='utf-8') as f:
        return f.read()


def write(p, s):
    with open(p, 'w', encoding='utf-8') as f:
        f.write(s)


def patch_manifest():
    p = os.path.join(A, 'app', 'src', 'main', 'AndroidManifest.xml')
    if not os.path.exists(p):
        sys.exit('AndroidManifest.xml not found — run `flutter create --platforms android,ios .` first')
    s = read(p)
    perms = ['INTERNET', 'ACCESS_FINE_LOCATION', 'ACCESS_COARSE_LOCATION', 'FOREGROUND_SERVICE',
             'FOREGROUND_SERVICE_LOCATION', 'POST_NOTIFICATIONS', 'WAKE_LOCK', 'CAMERA']
    add = ''.join(f'    <uses-permission android:name="android.permission.{x}"/>\n' for x in perms
                  if f'android.permission.{x}"' not in s)
    if add:
        s = re.sub(r'(<manifest[^>]*>\s*\n)', lambda m: m.group(1) + add, s, count=1)
    s = re.sub(r'android:label="[^"]*"', 'android:label="DriverGuardian"', s, count=1)
    if 'usesCleartextTraffic' not in s:
        s = s.replace('<application', '<application\n        android:usesCleartextTraffic="true"', 1)
    # security: the sign-in token must not leave the phone through Android backups / device transfer
    if 'android:allowBackup' not in s:
        s = s.replace('<application', '<application\n        android:allowBackup="false"\n        android:fullBackupContent="false"', 1)
    if 'default_notification_channel_id' not in s:
        s = s.replace('</application>', '        <meta-data android:name="com.google.firebase.messaging.default_notification_channel_id" android:value="dg_alerts"/>\n    </application>', 1)
    schemes = ['upi', 'tez', 'phonepe', 'paytmmp', 'tel', 'https']
    intents = ''.join(f'        <intent><action android:name="android.intent.action.VIEW"/><data android:scheme="{x}"/></intent>\n'
                      for x in schemes if f'android:scheme="{x}"' not in s)
    if intents:
        if '<queries>' in s:
            s = s.replace('<queries>', '<queries>\n' + intents.rstrip('\n'), 1)
        else:
            s = s.replace('</manifest>', '    <queries>\n' + intents + '    </queries>\n</manifest>', 1)
    write(p, s)
    print('patched', p)


# Newer AndroidX libraries (pulled in by the plugins) must be compiled against Android API 37.
# compileSdk only decides which APIs the code can see — minSdk (23) and the phones the app runs on do not change.
COMPILE_SDK = 37
# Google Play: new apps and updates must target Android 16 (API 36) or newer.
TARGET_SDK = 36


def patch_gradle_properties():
    p = os.path.join(A, 'gradle.properties')
    s = read(p) if os.path.exists(p) else ''
    if 'android.suppressUnsupportedCompileSdk' not in s:
        # an older Android Gradle plugin only warns about API 37 — silence the warning
        s = s.rstrip('\n') + f'\nandroid.suppressUnsupportedCompileSdk={COMPILE_SDK}\n'
        write(p, s)
    print('patched', p)


def patch_gradle():
    has_gs = os.path.exists(os.path.join(A, 'app', 'google-services.json'))
    kts_app = os.path.join(A, 'app', 'build.gradle.kts')
    groovy_app = os.path.join(A, 'app', 'build.gradle')
    if os.path.exists(kts_app):
        s = read(kts_app)
        s = re.sub(r'minSdk\s*=\s*flutter\.minSdkVersion', 'minSdk = maxOf(23, flutter.minSdkVersion)', s)
        s = re.sub(r'compileSdk\s*=\s*flutter\.compileSdkVersion', f'compileSdk = maxOf({COMPILE_SDK}, flutter.compileSdkVersion)', s)
        s = re.sub(r'targetSdk\s*=\s*flutter\.targetSdkVersion', f'targetSdk = maxOf({TARGET_SDK}, flutter.targetSdkVersion)', s)
        if has_gs and 'com.google.gms.google-services' not in s:
            # must come after com.android.application → append at the end of the plugins block
            s = re.sub(r'(plugins\s*\{[^}]*?)(\n\})', r'\1\n    id("com.google.gms.google-services")\2', s, count=1)
        write(kts_app, s)
        settings = os.path.join(A, 'settings.gradle.kts')
        if has_gs and os.path.exists(settings):
            t = read(settings)
            if 'com.google.gms.google-services' not in t:
                t = re.sub(r'(plugins\s*\{)', r'\1\n    id("com.google.gms.google-services") version "4.4.2" apply false', t, count=1)
                write(settings, t)
        print('patched', kts_app, '(firebase)' if has_gs else '')
    elif os.path.exists(groovy_app):
        s = read(groovy_app)
        s = re.sub(r'minSdkVersion\s+flutter\.minSdkVersion', 'minSdkVersion Math.max(23, flutter.minSdkVersion)', s)
        s = re.sub(r'minSdk\s*=\s*flutter\.minSdkVersion', 'minSdk = Math.max(23, flutter.minSdkVersion)', s)
        s = re.sub(r'compileSdkVersion\s+flutter\.compileSdkVersion', f'compileSdkVersion Math.max({COMPILE_SDK}, flutter.compileSdkVersion)', s)
        s = re.sub(r'compileSdk\s*=\s*flutter\.compileSdkVersion', f'compileSdk = Math.max({COMPILE_SDK}, flutter.compileSdkVersion)', s)
        s = re.sub(r'targetSdkVersion\s+flutter\.targetSdkVersion', f'targetSdkVersion Math.max({TARGET_SDK}, flutter.targetSdkVersion)', s)
        s = re.sub(r'targetSdk\s*=\s*flutter\.targetSdkVersion', f'targetSdk = Math.max({TARGET_SDK}, flutter.targetSdkVersion)', s)
        if has_gs and 'com.google.gms.google-services' not in s:
            s = re.sub(r'(plugins\s*\{[^}]*?)(\n\})', r'\1\n    id "com.google.gms.google-services"\2', s, count=1)
        write(groovy_app, s)
        settings = os.path.join(A, 'settings.gradle')
        if has_gs and os.path.exists(settings):
            t = read(settings)
            if 'com.google.gms.google-services' not in t:
                t = re.sub(r'(plugins\s*\{)', r'\1\n    id "com.google.gms.google-services" version "4.4.2" apply false', t, count=1)
                write(settings, t)
        print('patched', groovy_app, '(firebase)' if has_gs else '')
    else:
        print('WARNING: app/build.gradle(.kts) not found')


SIGN_KTS = '''    signingConfigs {
        create("release") {
            storeFile = file("upload-keystore.jks")
            storePassword = System.getenv("ANDROID_KEYSTORE_PASSWORD")
            keyAlias = System.getenv("ANDROID_KEY_ALIAS")
            keyPassword = System.getenv("ANDROID_KEY_PASSWORD")
        }
    }
'''
SIGN_GROOVY = '''    signingConfigs {
        release {
            storeFile file("upload-keystore.jks")
            storePassword System.getenv("ANDROID_KEYSTORE_PASSWORD")
            keyAlias System.getenv("ANDROID_KEY_ALIAS")
            keyPassword System.getenv("ANDROID_KEY_PASSWORD")
        }
    }
'''


def patch_signing():
    if not os.path.exists(os.path.join(A, 'app', 'upload-keystore.jks')):
        print('release signing: no upload-keystore.jks — release builds use the debug key (fine for sideloading)')
        return
    kts_app = os.path.join(A, 'app', 'build.gradle.kts')
    groovy_app = os.path.join(A, 'app', 'build.gradle')
    if os.path.exists(kts_app):
        p, block, old, new = kts_app, SIGN_KTS, r'signingConfig\s*=\s*signingConfigs\.getByName\("debug"\)', 'signingConfig = signingConfigs.getByName("release")'
    elif os.path.exists(groovy_app):
        p, block, old, new = groovy_app, SIGN_GROOVY, r'signingConfig\s+signingConfigs\.debug', 'signingConfig signingConfigs.release'
    else:
        print('WARNING: app/build.gradle(.kts) not found — signing not set')
        return
    s = read(p)
    if 'upload-keystore.jks' not in s:
        s = re.sub(r'(\n(\s*)buildTypes\s*\{)', lambda m: '\n' + block.rstrip('\n') + m.group(1), s, count=1)
    s = re.sub(old, new, s)
    write(p, s)
    print('release signing: upload key configured in', p)


def patch_ios():
    p = os.path.join(ROOT, 'ios', 'Runner', 'Info.plist')
    if not os.path.exists(p):
        return
    s = read(p)
    entries = {
        'NSLocationWhenInUseUsageDescription': '<string>Drivers share the bus location with parents and the school while a trip is running.</string>',
        'NSLocationAlwaysAndWhenInUseUsageDescription': '<string>Keeps sharing the bus location during a trip even if the screen turns off.</string>',
        'UIBackgroundModes': '<array><string>location</string><string>remote-notification</string></array>',
        'LSApplicationQueriesSchemes': '<array><string>upi</string><string>tez</string><string>phonepe</string><string>paytmmp</string><string>tel</string></array>',
        'NSCameraUsageDescription': '<string>Drivers scan students\u2019 QR bus passes to mark boarding and drop.</string>',
        'NSPhotoLibraryUsageDescription': '<string>Attach a photo to an incident report or complaint.</string>',
        'CFBundleDisplayName': '<string>DriverGuardian</string>',
    }
    for k, v in entries.items():
        if f'<key>{k}</key>' in s:
            if k == 'CFBundleDisplayName':
                s = re.sub(r'(<key>CFBundleDisplayName</key>\s*)<string>[^<]*</string>', r'\1' + v, s)
            continue
        s = s.replace('</dict>\n</plist>', f'\t<key>{k}</key>\n\t{v}\n</dict>\n</plist>', 1)
    write(p, s)
    print('patched', p)


def patch_podfile():
    """permission_handler on iOS: enable only the permissions the app uses (needs ios/Podfile — created on the first iOS build on a Mac; re-run this script then)."""
    p = os.path.join(ROOT, 'ios', 'Podfile')
    if not os.path.exists(p):
        return
    s = read(p)
    if 'PERMISSION_LOCATION' in s:
        return
    block = ("    target.build_configurations.each do |config|\n"
             "      config.build_settings['GCC_PREPROCESSOR_DEFINITIONS'] ||= ['$(inherited)', 'PERMISSION_LOCATION=1', 'PERMISSION_CAMERA=1', 'PERMISSION_NOTIFICATIONS=1']\n"
             "    end\n")
    s2 = re.sub(r'(flutter_additional_ios_build_settings\(target\)\n)', lambda m: m.group(1) + block, s, count=1)
    if s2 != s:
        write(p, s2)
        print('patched', p)


def patch_lint():
    """Release builds run Android lint ("lintVital") on every plugin. Newer lint versions can crash on plugin
    sources (e.g. image_picker: NoSuchMethodError List.removeLast) — that check is not needed to build the app,
    so it is switched off for all modules. Code quality is still checked by flutter analyze."""
    marker = 'DriverGuardian: skip lintVital'
    for name, block in (
        ('build.gradle.kts', '\n// ' + marker + '\nsubprojects {\n    tasks.configureEach {\n        if (name.startsWith("lintVital")) enabled = false\n    }\n}\n'),
        ('build.gradle', '\n// ' + marker + '\nsubprojects {\n    tasks.configureEach { t ->\n        if (t.name.startsWith("lintVital")) t.enabled = false\n    }\n}\n'),
    ):
        p = os.path.join(A, name)
        if os.path.exists(p):
            s = read(p)
            if marker not in s:
                write(p, s.rstrip('\n') + '\n' + block)
            print('patched', p, '(lint)')
            return


if __name__ == '__main__':
    patch_manifest()
    patch_gradle()
    patch_gradle_properties()
    patch_lint()
    patch_signing()
    patch_ios()
    patch_podfile()
